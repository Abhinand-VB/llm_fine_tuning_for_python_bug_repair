"""Tables, charts and qualitative examples from the training and evaluation runs
(PROJECT_PLAN.md, Phase 6).

Reads whatever of these exist (missing runs are shown as "-"):
    results/train_{lora,qlora}.json                      from src/train.py
    results/eval_{baseline,lora,qlora}_{set}.json         from src/evaluate.py

Writes:
    results/summary.md        main results table, per-round repair, breakdown by bug type, efficiency
    results/summary.json      the same numbers, machine-readable
    results/examples.md       qualitative examples: fine-tuned repairs the baseline missed, shared
                              failures, and unchanged (no-op) answers
    results/figures/*.png     repair rate by round, accuracy vs compute, repair by bug type,
                              training loss curves

Usage:
    python src/analyze.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
RESULTS = ROOT / "results"
FIGURES = RESULTS / "figures"

SYSTEMS = ("baseline", "lora", "qlora")
LABELS = {"baseline": "Baseline (prompt-only)", "lora": "LoRA", "qlora": "QLoRA"}
EVAL_SETS = ("mbpp", "humaneval", "humaneval-gen")
SET_LABELS = {"mbpp": "MBPP test mutants", "humaneval": "HumanEval mutants",
              "humaneval-gen": "HumanEval generate + repair"}

# Categorical slots 1-3 of the reference palette (validated with the dataviz validator; the
# aqua slot sits below 3:1 on white, so every chart carries direct labels and markers too).
COLORS = {"baseline": "#2a78d6", "lora": "#eb6834", "qlora": "#1baf7a"}
MARKERS = {"baseline": "o", "lora": "s", "qlora": "^"}
INK, INK_2, GRID = "#0b0b0b", "#52514e", "#e4e3df"


def load(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pct(x):
    return "-" if x is None else f"{100 * x:.1f}%"


def num(x, fmt="{:,}"):
    return "-" if x is None else fmt.format(x)


# ------------------------------------------------------------------ gathering

def gather():
    train = {s: load(RESULTS / f"train_{s}.json") for s in ("lora", "qlora")}
    evals = {(s, e): load(RESULTS / f"eval_{s}_{e}.json") for s in SYSTEMS for e in EVAL_SETS}
    return train, evals


def summary_rows(train, evals):
    rows = {}
    for s in SYSTEMS:
        t = train.get(s) or {}
        row = {
            "trainable_params": t.get("trainable_params", 0 if s == "baseline" else None),
            "trainable_percent": t.get("trainable_percent", 0.0 if s == "baseline" else None),
            "train_minutes": t.get("train_minutes", 0.0 if s == "baseline" else None),
            "train_peak_gpu_gb": t.get("peak_gpu_memory_gb"),
            "final_train_loss": t.get("final_train_loss"),
            "train_max_steps": t.get("max_steps"),
            "train_host": t.get("host"),
        }
        for e in EVAL_SETS:
            r = evals.get((s, e))
            if not r:
                continue
            m, eff = r["metrics"], r["efficiency"]
            row[e] = {
                "n": m["n_tasks"], "pass_rate": m["pass_rate"],
                "pass_at_1": m.get("pass_at_1"),
                "repair_rate_by_round": m["repair_rate_by_round"],
                "by_bug_type": m["by_bug_type"], "by_level": m["by_level"],
                "unchanged_rate_round1": m["unchanged_rate_round1"],
                "seconds_per_task": eff["seconds_per_task"],
                "eval_peak_gpu_gb": eff["peak_gpu_memory_gb"],
                "few_shot": r.get("few_shot"), "device": r.get("device"),
            }
        rows[s] = row
    return rows


# ------------------------------------------------------------------ markdown

def get(rows, s, e, key):
    return (rows[s].get(e) or {}).get(key)


def write_summary(rows):
    L = ["# Results", "",
         "Generated by `python src/analyze.py` from `results/train_*.json` and "
         "`results/eval_*.json`. Greedy decoding, up to 3 repair rounds; a dash means that run "
         "is missing.", ""]

    L += ["## Main results", "",
          "| System | Trainable params | MBPP pass rate | HumanEval mutants pass rate | "
          "HumanEval pass@1 | HumanEval after repair | Train time (min) | Train peak GPU (GB) |",
          "|---|---|---|---|---|---|---|---|"]
    for s in SYSTEMS:
        r = rows[s]
        tp = r["trainable_params"]
        tp_txt = "0" if tp == 0 else (f"{tp / 1e6:.2f}M ({r['trainable_percent']}%)" if tp else "-")
        L.append(f"| {LABELS[s]} | {tp_txt} | {pct(get(rows, s, 'mbpp', 'pass_rate'))} | "
                 f"{pct(get(rows, s, 'humaneval', 'pass_rate'))} | "
                 f"{pct(get(rows, s, 'humaneval-gen', 'pass_at_1'))} | "
                 f"{pct(get(rows, s, 'humaneval-gen', 'pass_rate'))} | "
                 f"{num(r['train_minutes'], '{:.1f}')} | {num(r['train_peak_gpu_gb'], '{:.2f}')} |")
    L.append("")

    L += ["## Repair rate by round", "",
          "Share of initially failing programs fixed by round k (cumulative). For the mutant sets "
          "every program fails at the start; for HumanEval generate + repair the denominator is "
          "the tasks whose first attempt failed.", "",
          "| System | Eval set | Round 1 | Round 2 | Round 3 | Unchanged answers (round 1) |",
          "|---|---|---|---|---|---|"]
    for e in EVAL_SETS:
        for s in SYSTEMS:
            rr = get(rows, s, e, "repair_rate_by_round")
            if not rr:
                continue
            L.append(f"| {LABELS[s]} | {SET_LABELS[e]} | {pct(rr.get('1'))} | {pct(rr.get('2'))} | "
                     f"{pct(rr.get('3'))} | {pct(get(rows, s, e, 'unchanged_rate_round1'))} |")
    L.append("")

    L += ["## MBPP repair rate by bug type", ""]
    types = []
    for s in SYSTEMS:
        for t in (get(rows, s, "mbpp", "by_bug_type") or {}):
            if t not in types:
                types.append(t)
    if types:
        L += ["| Bug type | n | " + " | ".join(LABELS[s] for s in SYSTEMS) + " |",
              "|---|---|" + "---|" * len(SYSTEMS)]
        for t in types:
            n = next((get(rows, s, "mbpp", "by_bug_type")[t]["n"] for s in SYSTEMS
                      if t in (get(rows, s, "mbpp", "by_bug_type") or {})), "-")
            cells = [pct(((get(rows, s, "mbpp", "by_bug_type") or {}).get(t) or {}).get("repair_rate"))
                     for s in SYSTEMS]
            L.append(f"| {t} | {n} | " + " | ".join(cells) + " |")
        L.append("")

    L += ["## Efficiency", "",
          "| System | Final train loss | Train steps | Eval s/task (MBPP) | Eval peak GPU (GB, MBPP) | "
          "Few-shot | Device |", "|---|---|---|---|---|---|---|"]
    for s in SYSTEMS:
        r = rows[s]
        steps = "-" if s == "baseline" else ("full" if r["train_max_steps"] == -1 else
                                             num(r["train_max_steps"]))
        L.append(f"| {LABELS[s]} | {num(r['final_train_loss'], '{:.4f}')} | {steps} | "
                 f"{num(get(rows, s, 'mbpp', 'seconds_per_task'), '{:.2f}')} | "
                 f"{num(get(rows, s, 'mbpp', 'eval_peak_gpu_gb'), '{:.2f}')} | "
                 f"{num(get(rows, s, 'mbpp', 'few_shot'))} | {get(rows, s, 'mbpp', 'device') or '-'} |")
    L.append("")
    L += ["## Figures", "",
          "![Repair rate by round](figures/repair_by_round.png)", "",
          "![Accuracy vs compute](figures/accuracy_vs_compute.png)", "",
          "![Repair rate by bug type](figures/repair_by_bug_type.png)", "",
          "![Training loss](figures/loss_curves.png)", ""]
    (RESULTS / "summary.md").write_text("\n".join(L), encoding="utf-8")


# ------------------------------------------------------------------ figures

def style(ax, title, ylabel, xlabel=None):
    ax.set_title(title, color=INK, fontsize=11, loc="left")
    ax.set_ylabel(ylabel, color=INK_2, fontsize=9)
    if xlabel:
        ax.set_xlabel(xlabel, color=INK_2, fontsize=9)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_2, labelsize=8)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def fig_repair_by_round(plt, rows):
    sets = [e for e in ("mbpp", "humaneval") if any(get(rows, s, e, "repair_rate_by_round")
                                                     for s in SYSTEMS)]
    if not sets:
        return
    fig, axes = plt.subplots(1, len(sets), figsize=(5.2 * len(sets), 3.6), squeeze=False)
    for ax, e in zip(axes[0], sets):
        ends = []
        for s in SYSTEMS:
            rr = get(rows, s, e, "repair_rate_by_round")
            if not rr:
                continue
            ks = sorted(int(k) for k in rr)
            ys = [100 * rr[str(k)] for k in ks]
            ax.plot(ks, ys, color=COLORS[s], linewidth=2, marker=MARKERS[s], markersize=7,
                    markeredgecolor="white", markeredgewidth=1.5, label=LABELS[s])
            ends.append([ys[-1], ys[-1], f"{LABELS[s].split(' ')[0]} {ys[-1]:.1f}%", ks[-1]])
        # Direct end labels, nudged apart (>= 5 points on the y scale) so close values stay legible.
        ends.sort(key=lambda t: t[0])
        for j in range(1, len(ends)):
            ends[j][1] = max(ends[j][1], ends[j - 1][1] + 5)
        for y, label_y, text, k in ends:
            ax.annotate(text, (k, y), xytext=(k + 0.08, label_y), textcoords="data",
                        va="center", fontsize=8, color=INK)
        ax.set_xticks([1, 2, 3])
        ax.set_xlim(0.8, 3.7)
        ax.set_ylim(0, 100)
        style(ax, SET_LABELS[e], "Repaired by round k (%)", "Repair round")
    axes[0][0].legend(frameon=False, fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig(FIGURES / "repair_by_round.png", dpi=200)
    plt.close(fig)


def fig_accuracy_vs_compute(plt, rows):
    pts = [(s, rows[s]["train_minutes"], get(rows, s, "mbpp", "pass_rate"),
            rows[s]["train_peak_gpu_gb"]) for s in SYSTEMS]
    pts = [p for p in pts if p[1] is not None and p[2] is not None]
    if not pts:
        return
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    for s, minutes, acc, mem in pts:
        ax.scatter([minutes], [100 * acc], s=90, color=COLORS[s], marker=MARKERS[s],
                   edgecolors="white", linewidths=2, zorder=3)
        mem_txt = f", {mem:.1f} GB" if mem else ""
        # QLoRA's label goes below its point so it never collides with LoRA's, which sits close above.
        offset = (8, -14) if s == "qlora" else (8, 4)
        ax.annotate(f"{LABELS[s].split(' ')[0]} ({100 * acc:.1f}%{mem_txt})", (minutes, 100 * acc),
                    xytext=offset, textcoords="offset points", fontsize=8, color=INK)
    xmax = max(p[1] for p in pts)
    ax.set_xlim(-0.05 * max(xmax, 1), 1.45 * max(xmax, 1))
    ax.set_ylim(0, 100)
    style(ax, "MBPP pass rate vs training time", "Pass rate after 3 rounds (%)",
          "Training time (min); labels show peak training GPU memory")
    fig.tight_layout()
    fig.savefig(FIGURES / "accuracy_vs_compute.png", dpi=200)
    plt.close(fig)


def fig_by_bug_type(plt, rows):
    present = [s for s in SYSTEMS if get(rows, s, "mbpp", "by_bug_type")]
    if not present:
        return
    types = list(get(rows, present[0], "mbpp", "by_bug_type"))
    fig, ax = plt.subplots(figsize=(max(6, 1.15 * len(types) + 2), 3.8))
    width = 0.8 / len(present)
    for j, s in enumerate(present):
        bt = get(rows, s, "mbpp", "by_bug_type")
        xs = [i + (j - (len(present) - 1) / 2) * width for i in range(len(types))]
        ys = [100 * (bt.get(t) or {}).get("repair_rate", 0) for t in types]
        # A white edge gives the 2px surface gap between adjacent bars.
        ax.bar(xs, ys, width=width, color=COLORS[s], edgecolor="white", linewidth=1.5,
               label=LABELS[s])
    n = get(rows, present[0], "mbpp", "by_bug_type")
    ax.set_xticks(range(len(types)))
    ax.set_xticklabels([t.replace("+", "+\n") + f"\n(n={n[t]['n']})" for t in types], fontsize=7)
    ax.set_ylim(0, 100)
    style(ax, "MBPP repair rate by bug type (after 3 rounds)", "Repaired (%)")
    ax.legend(frameon=False, fontsize=8, ncol=len(present), loc="upper right")
    fig.tight_layout()
    fig.savefig(FIGURES / "repair_by_bug_type.png", dpi=200)
    plt.close(fig)


def fig_loss(plt, train):
    present = [s for s in ("lora", "qlora") if train.get(s) and train[s].get("log_history")]
    if not present:
        return
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    for s in present:
        hist = train[s]["log_history"]
        tr = [(h["step"], h["loss"]) for h in hist if "loss" in h]
        ev = [(h["step"], h["eval_loss"]) for h in hist if "eval_loss" in h]
        if tr:
            # Both train curves converge near zero, so end labels would overlap; the legend names them.
            ax.plot(*zip(*tr), color=COLORS[s], linewidth=2, label=f"{LABELS[s]} train")
        if ev:
            ax.plot(*zip(*ev), color=COLORS[s], linewidth=0, marker=MARKERS[s], markersize=8,
                    markeredgecolor="white", markeredgewidth=1.5, label=f"{LABELS[s]} validation")
    style(ax, "Training loss (fixed-code tokens only)", "Loss", "Optimizer step")
    ax.legend(frameon=False, fontsize=8)
    ax.set_ylim(bottom=0)
    fig.tight_layout()
    fig.savefig(FIGURES / "loss_curves.png", dpi=200)
    plt.close(fig)


# ------------------------------------------------------------------ qualitative examples

def write_examples(evals, k=3):
    from data import load_eval_set

    base = evals.get(("baseline", "mbpp"))
    tuned = next(((s, evals[(s, "mbpp")]) for s in ("lora", "qlora") if evals.get((s, "mbpp"))), None)
    if not base or not tuned:
        return
    name, tuned = tuned
    data = load_eval_set("mbpp", len(base["per_task"]))
    L = ["# Qualitative examples (MBPP test mutants)", "",
         f"Baseline vs {LABELS[name]}. Code is the final program each system produced.", ""]

    def block(title, i):
        ex, b, t = data[i], base["per_task"][i], tuned["per_task"][i]
        last = lambda row: row["rounds"][-1]["code"] if row["rounds"] else ""
        return [f"### {title}: task {ex['task_id']} ({ex['bug_type']}, {ex['mutation']})", "",
                f"**Problem:** {ex['problem']}", "", "**Buggy code**", "```python",
                ex["buggy_code"], "```", "", f"**Initial feedback**", "```", ex["feedback"], "```", "",
                f"**Baseline** (solved round {b['solved_round']})", "```python", last(b), "```", "",
                f"**{LABELS[name]}** (solved round {t['solved_round']})", "```python", last(t),
                "```", ""]

    n = min(len(base["per_task"]), len(tuned["per_task"]))
    won = [i for i in range(n) if tuned["per_task"][i]["solved_round"] is not None
           and base["per_task"][i]["solved_round"] is None]
    lost = [i for i in range(n) if tuned["per_task"][i]["solved_round"] is None
            and base["per_task"][i]["solved_round"] is not None]
    both_fail = [i for i in range(n) if tuned["per_task"][i]["solved_round"] is None
                 and base["per_task"][i]["solved_round"] is None]
    noop = [i for i in range(n) if base["per_task"][i]["rounds"]
            and base["per_task"][i]["rounds"][0].get("unchanged")]
    L += [f"Counts over {n} tasks: {LABELS[name]} fixed {len(won)} the baseline missed; the "
          f"baseline fixed {len(lost)} that {LABELS[name]} missed; {len(both_fail)} unsolved by "
          f"both; the baseline returned the buggy code unchanged in round 1 on {len(noop)}.", ""]
    for title, idx in ((f"{LABELS[name]} repairs, baseline fails", won),
                       (f"Baseline repairs, {LABELS[name]} fails", lost),
                       ("Both fail", both_fail),
                       ("Baseline returns the bug unchanged", noop)):
        for i in idx[:k]:
            L += block(title, i)
    (RESULTS / "examples.md").write_text("\n".join(L), encoding="utf-8")


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    FIGURES.mkdir(parents=True, exist_ok=True)
    train, evals = gather()
    rows = summary_rows(train, evals)
    (RESULTS / "summary.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    write_summary(rows)
    fig_repair_by_round(plt, rows)
    fig_accuracy_vs_compute(plt, rows)
    fig_by_bug_type(plt, rows)
    fig_loss(plt, train)
    write_examples(evals)
    found = [f"train_{s}" for s in train if train[s]] + [f"eval_{s}_{e}" for (s, e) in evals
                                                          if evals[(s, e)]]
    print(f"Read {len(found)} result files: {', '.join(found) or 'none'}")
    print(f"Wrote results/summary.md, summary.json, examples.md and figures/")


if __name__ == "__main__":
    main()
